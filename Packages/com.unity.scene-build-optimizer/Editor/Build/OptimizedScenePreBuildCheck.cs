using System.Collections.Generic;
using UnityEditor;
using UnityEditor.Build;
using UnityEditor.Build.Profile;
using UnityEditor.Build.Reporting;
using UnityEngine;

namespace SceneBuildOptimizer.Editor.Build
{
    /// <summary>
    /// Runs before every build. Unlike IProcessSceneWithReport, this callback has no per-scene build
    /// cache to skip it and no restriction against touching assets other than the scene — it's
    /// ordinary editor scripting — so it reliably enforces that every optimized scene about to be
    /// built is up to date with its source, regenerating any that are stale.
    /// </summary>
    public sealed class OptimizedScenePreBuildCheck : IPreprocessBuildWithReport
    {
        public int callbackOrder => 0;

        public void OnPreprocessBuild(BuildReport report)
        {
            Debug.Log("Scene Build Optimizer: pre-build check running.");

            BuildProfile activeProfile = null;
            try
            {
                activeProfile = BuildProfile.GetActiveBuildProfile();
            }
            catch
            {
                // BuildProfile API unavailable/changed in this Unity version — fall back to global Build Settings below.
            }

            int sceneCount = 0;
            foreach (var scenePath in GetScenesForActiveBuild(activeProfile, logSource: true))
            {
                sceneCount++;
                var manifest = OptimizedSceneManifest.Load(scenePath);
                if (manifest == null)
                {
                    Debug.Log($"Scene Build Optimizer: '{scenePath}' has no manifest — not an optimized scene generated by this tool, skipping.");
                    continue;
                }

                if (manifest.IsStale())
                {
                    Debug.Log($"Scene Build Optimizer: '{scenePath}' is stale relative to its source ('{manifest.SourceScenePath}') — regenerating before build.");
                    // Pass the same profile we resolved the scene list against, so the optimizers that
                    // run here use exactly the settings/enabled-state this build should actually get.
                    OptimizedSceneGenerator.Generate(manifest.SourceScenePath, scenePath, activeProfile);
                }
                else
                {
                    Debug.Log($"Scene Build Optimizer: '{scenePath}' is up to date.");
                }
            }

            Debug.Log($"Scene Build Optimizer: pre-build check done — checked {sceneCount} scene(s).");
        }

        static IEnumerable<string> GetScenesForActiveBuild(BuildProfile activeProfile, bool logSource = false)
        {
            if (activeProfile != null && activeProfile.overrideGlobalScenes && activeProfile.scenes != null)
            {
                if (logSource)
                    Debug.Log($"Scene Build Optimizer: active BuildProfile is '{activeProfile.name}', overrideGlobalScenes=true — using its scene list.");

                foreach (var scene in activeProfile.scenes)
                {
                    if (scene.enabled)
                        yield return scene.path;
                }
                yield break;
            }

            if (logSource)
            {
                string reason = activeProfile == null
                    ? "no active BuildProfile"
                    : $"active BuildProfile '{activeProfile.name}' has overrideGlobalScenes={activeProfile.overrideGlobalScenes}";
                Debug.Log($"Scene Build Optimizer: {reason} — falling back to global EditorBuildSettings.scenes.");
            }

            foreach (var scene in EditorBuildSettings.scenes)
            {
                if (scene.enabled)
                    yield return scene.path;
            }
        }
    }
}
